"""Generates the launcher icon from one geometry: SVG + HTML preview, and Android vectors.

Run from the repo root:  python3 scripts/make_icon.py
Then render PNGs:        see scripts/render_icon.sh
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PURPLE = "#6750A4"
LAVENDER = "#EADDFF"
WHITE = "#FFFFFF"
C = 54.0  # adaptive icon viewport is 108 x 108, safe zone is a 66 dp circle


def cookie(cx, cy, r, bumps=8, depth=0.075, steps=240):
    """MaterialShapes-style cookie: a circle with soft scallops."""
    pts = []
    for i in range(steps):
        t = 2 * math.pi * i / steps
        rr = r * (1 + depth * math.cos(bumps * t))
        pts.append((cx + rr * math.cos(t - math.pi / 2), cy + rr * math.sin(t - math.pi / 2)))
    d = "M%.2f,%.2f" % pts[0] + "".join("L%.2f,%.2f" % p for p in pts[1:]) + "Z"
    return d


def sparkle(cx, cy, r, pinch=0.12):
    """Four-point star with curved sides."""
    k = r * pinch
    return (
        f"M{cx:.2f},{cy - r:.2f}"
        f"Q{cx + k:.2f},{cy - k:.2f} {cx + r:.2f},{cy:.2f}"
        f"Q{cx + k:.2f},{cy + k:.2f} {cx:.2f},{cy + r:.2f}"
        f"Q{cx - k:.2f},{cy + k:.2f} {cx - r:.2f},{cy:.2f}"
        f"Q{cx - k:.2f},{cy - k:.2f} {cx:.2f},{cy - r:.2f}Z"
    )


COOKIE = cookie(C - 3, C + 3, 22)
STAR = sparkle(C - 3, C + 3, 14)
SMALL = sparkle(C + 19, C - 19, 5.5)


def svg(size=108, rounded=False):
    clip = '<clipPath id="c"><rect x="18" y="18" width="72" height="72" rx="16"/></clipPath>' if rounded else ""
    g = ' clip-path="url(#c)"' if rounded else ""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="{size}" height="{size}">
  <defs>{clip}</defs>
  <g{g}>
    <rect x="0" y="0" width="108" height="108" fill="{PURPLE}"/>
    <path d="{COOKIE}" fill="{LAVENDER}"/>
    <path d="{STAR}" fill="{PURPLE}"/>
    <path d="{SMALL}" fill="{WHITE}"/>
  </g>
</svg>
"""


def vector(paths):
    body = "\n".join(
        f'    <path\n        android:fillColor="{color}"\n        android:pathData="{d}" />' for d, color in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_icon.py. Edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


import sys

if len(sys.argv) == 4 and sys.argv[1] == "--svg":
    # Size-specific SVG for rendering, e.g. --svg 1024 rounded /tmp/x.svg
    pathlib.Path(sys.argv[3]).write_text(svg(int(sys.argv[2].split(":")[0]), rounded=sys.argv[2].endswith(":rounded")))
    sys.exit(0)

art = ROOT / "art" / "icon"
art.mkdir(parents=True, exist_ok=True)
(art / "icon.svg").write_text(svg(512))
(art / "icon-rounded.svg").write_text(svg(512, rounded=True))
(art / "icon.html").write_text(f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>M3 Expressive Paywall icon</title>
<style>
  html, body {{ margin: 0; background: transparent; }}
  .icon {{ width: 100vmin; height: 100vmin; display: block; }}
</style>
</head>
<body>
<!-- Flat purple launcher icon: a MaterialShapes cookie with a sparkle, meaning "unlock Pro". -->
{svg(512).replace('width="512" height="512"', 'class="icon"')}
</body>
</html>
""")

res = ROOT / "app" / "src" / "main" / "res"
(res / "drawable" / "ic_launcher_background.xml").write_text(vector([("M0,0h108v108h-108z", PURPLE)]))
(res / "drawable" / "ic_launcher_foreground.xml").write_text(
    vector([(COOKIE, LAVENDER), (STAR, PURPLE), (SMALL, WHITE)])
)
# Themed icon: the system tints this single-color layer. The star is cut out of the cookie.
(res / "drawable" / "ic_launcher_monochrome.xml").write_text(
    vector([(COOKIE + STAR, "#FF000000"), (SMALL, "#FF000000")]).replace(
        'android:pathData="' + COOKIE + STAR + '"',
        'android:fillType="evenOdd"\n        android:pathData="' + COOKIE + STAR + '"',
    )
)
adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
    (res / "mipmap-anydpi-v26" / name).write_text(adaptive)
print("icon sources written")
